# 预编译：匹配所有康熙部首的正则模式
_KANGXI_RE = re.compile('|'.join(re.escape(k) for k in KANGXI_TO_CJK))


def apply_md_formatting(text, level1_pattern, level2_pattern, level3_pattern, level4_pattern):
    """
    根据用户配置的正则表达式为原文添加 Markdown 格式。
    已剥离所有硬编码和特殊前言逻辑，仅保留底层洗白与纯粹正则。
    """
    # ---- 第一步：Unicode 康熙部首强制洗白 ----
    text = _KANGXI_RE.sub(lambda m: KANGXI_TO_CJK[m.group(0)], text)

    # ---- 第二步：图片残留清理 ----
    # Markdown 图片: ![alt](url)
    text = re.sub(r'!\[([^\]]*)\]\([^)]+\)', '', text)
    # Markdown 图片无链接: ![alt]
    text = re.sub(r'!\[([^\]]*)\]', '', text)
    # base64 内联图片（MarkItDown 常见产物）
    text = re.sub(r'data:image/[^;]+;base64,[A-Za-z0-9+/=]+', '', text)
    # HTML <img> 标签
    text = re.sub(r'<img[^>]*/?>', '', text, flags=re.IGNORECASE)
    # 纯图片 URL 行（整行只是图片链接）
    text = re.sub(r'^\s*https?://\S+\.(?:png|jpg|jpeg|gif|svg|bmp|webp)\S*\s*$', '', text, flags=re.MULTILINE | re.IGNORECASE)

    # 收拢多余空行
    text = re.sub(r'\n{3,}', '\n\n', text)

    lines = text.split('\n')
    formatted_lines = []

    # 构建层级模式映射
    patterns = [
        (level1_pattern, '#'),
        (level2_pattern, '##'),
        (level3_pattern, '###'),
        (level4_pattern, '####'),
    ]

    for line in lines:
        line_stripped = line.strip()
        if not line_stripped:
            formatted_lines.append(line)
            continue

        # 检查是否已有 Markdown 标题符号（行首 #），有则跳过
        if re.match(r'^#{1,6}\s', line_stripped):
            formatted_lines.append(line)
            continue

        # 按层级逐一匹配
        matched = False
        for pattern, md_format in patterns:
            if pattern:
                try:
                    if re.match(pattern, line_stripped) or re.search(pattern, line_stripped):
                        formatted_line = f"{md_format} {line_stripped}"
                        formatted_lines.append(formatted_line)
                        matched = True
                        break
                except re.error:
                    continue

        if not matched:
            formatted_lines.append(line)

    return '\n'.join(formatted_lines)
